-- scripts/gen-dungeons.lua -- generates modules/InstanceTracker/core/DungeonData.lua
--
-- Usage (from the repo root):
--   lua scripts/gen-dungeons.lua "<AddOns>/NaowhForever_DungeonJournal/Data/Dungeons"
--
-- Extracts ONLY game data (owner decision, docs/11): instanceID, encounterIDs, boss order,
-- the rare flag and the English encounter name (needed to match the lockout list, which only
-- gives names). No code, texts, loot, models or NPC ids are copied. Bosses without an
-- encounterID are skipped: they never appear in the lockout list nor fire ENCOUNTER_END.
-- MEASURED holds names seen in game that differ from the source (they win over it).
local dir = arg[1]
if not dir then
  io.stderr:write("usage: lua scripts/gen-dungeons.lua <NF Data/Dungeons dir>\n")
  os.exit(1)
end
local OUT = "QuantumDungeonTools/modules/InstanceTracker/core/DungeonData.lua"

-- encounterID -> extra names measured in game (Forever 1.60.1, enUS).
local MEASURED = {
  [3355] = { "The Butcher" }, -- Ruins of Lordaeron, ENCOUNTER_END + lockout (2026-11-13)
}

local list = {}
_G.NaowhForever = { Journal = { AddDungeon = function(key, d) list[#list + 1] = { key = key, d = d } end } }

local files = {}
local p = assert(io.popen('ls "' .. dir .. '"'))
for f in p:lines() do
  if f:match("%.lua$") then files[#files + 1] = f end
end
p:close()
table.sort(files)
for _, f in ipairs(files) do dofile(dir .. "/" .. f) end
table.sort(list, function(a, b) return a.key < b.key end)

local function q(s) return string.format("%q", s) end

local out = {
  "-- modules/InstanceTracker/core/DungeonData.lua -- GENERATED by scripts/gen-dungeons.lua: DO NOT EDIT.",
  "--",
  "-- Game data only (owner, docs/11): instanceID, encounterIDs in route order, rare flag and",
  "-- English encounter names. Source: the data files of NaowhForever_DungeonJournal (generated",
  "-- by its author from the game client) plus names measured in game by QDT.",
  "-- Rares are listed but never count for 'Bosses X/Y' nor for the end of the run.",
  "local _, ns = ...",
  "",
  "ns.InstanceDungeonData = {",
}
local nDungeons, nBosses, nRares = 0, 0, 0
for _, e in ipairs(list) do
  local d = e.d
  local rows, seen = {}, {}
  for _, w in ipairs(d.wings or {}) do
    for _, b in ipairs(w.bosses or {}) do
      if not b.trash and b.encounters and #b.encounters > 0 then
        local first = b.encounters[1]
        if seen[first] then
          -- Same encounter listed twice (e.g. Sneed and his Shredder): one boss, two names.
          local names = seen[first].names
          names[#names + 1] = b.name
        else
          local names = { b.name }
          for _, id in ipairs(b.encounters) do
            for _, n in ipairs(MEASURED[id] or {}) do table.insert(names, 1, n) end
          end
          local row = { ids = b.encounters, names = names, rare = b.rare }
          seen[first] = row
          rows[#rows + 1] = row
        end
      end
    end
  end
  if d.instance and #rows > 0 then
    nDungeons = nDungeons + 1
    out[#out + 1] = string.format("  { key = %s, instance = %d, bosses = {", q(e.key), d.instance)
    for _, r in ipairs(rows) do
      local qn = {}
      for i, n in ipairs(r.names) do qn[i] = q(n) end
      out[#out + 1] = string.format("    { ids = { %s }, names = { %s }%s },",
        table.concat(r.ids, ", "), table.concat(qn, ", "), r.rare and ", rare = true" or "")
      nBosses = nBosses + 1
      if r.rare then nRares = nRares + 1 end
    end
    out[#out + 1] = "  } },"
  end
end
out[#out + 1] = "}"
out[#out + 1] = ""

local f = assert(io.open(OUT, "wb"))
f:write(table.concat(out, "\n"))
f:close()
print(string.format("%s: %d dungeons, %d bosses (%d rares)", OUT, nDungeons, nBosses, nRares))
