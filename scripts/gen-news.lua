-- scripts/gen-news.lua -- generates QuantumDungeonTools/core/NewsData.lua from CHANGELOG.md
--
-- Usage (from the repo root), after editing the CHANGELOG and before every release:
--   lua scripts/gen-news.lua
--
-- The "What's new" page of the main window reads ONLY this data (owner, 2026-11-14): one source
-- of text, the CHANGELOG. Parsing lives in core/News.lua (pure, with specs); this script only
-- keeps the newest News.MAX versions and serialises them.
local SRC, OUT = "CHANGELOG.md", "QuantumDungeonTools/core/NewsData.lua"

local ns = {}
assert(loadfile("QuantumDungeonTools/core/News.lua"))("QuantumDungeonTools", ns)
local News = ns.News

local fh = assert(io.open(SRC, "rb"))
local md = fh:read("*a")
fh:close()

local all = News.parse(md)
local list, more = News.recent(all)

local function q(s) return string.format("%q", s) end

-- A long string as `"piece " ..` lines of at most WRAP bytes (luacheck: 120 columns). Cuts only
-- at spaces, so a multibyte UTF-8 character is never split.
local WRAP = 90
local function qwrap(s, indent)
  local pieces, cur = {}, ""
  for word in s:gmatch("%S+%s*") do
    if #cur > 0 and #cur + #word > WRAP then
      pieces[#pieces + 1], cur = cur, ""
    end
    cur = cur .. word
  end
  pieces[#pieces + 1] = cur
  for i = 1, #pieces do pieces[i] = q(pieces[i]) end
  return table.concat(pieces, " ..\n" .. indent)
end

local out = {
  "-- core/NewsData.lua -- GENERATED by scripts/gen-news.lua from CHANGELOG.md: DO NOT EDIT.",
  "-- The newest versions shown on the \"What's new\" page (core/News.lua, wow/MainWindow.lua).",
  "local _, ns = ...",
  "",
  "ns.NewsData = {",
  "  more = " .. tostring(more) .. ",",
  "  versions = {",
}
local nItems = 0
for _, v in ipairs(list) do
  out[#out + 1] = "    {"
  if v.version then out[#out + 1] = "      version = " .. q(v.version) .. "," end
  if v.date then out[#out + 1] = "      date = " .. q(v.date) .. "," end
  out[#out + 1] = "      unreleased = " .. tostring(v.unreleased) .. ","
  out[#out + 1] = "      sections = {"
  for _, s in ipairs(v.sections) do
    out[#out + 1] = "        { name = " .. q(s.name) .. ", items = {"
    for _, it in ipairs(s.items) do
      nItems = nItems + 1
      out[#out + 1] = "          {"
      if it.title then out[#out + 1] = "            title = " .. qwrap(it.title, "              ") .. "," end
      out[#out + 1] = "            sep = " .. q(it.sep) .. ","
      out[#out + 1] = "            body = " .. qwrap(it.body, "              ") .. ","
      out[#out + 1] = "          },"
    end
    out[#out + 1] = "        } },"
  end
  out[#out + 1] = "      },"
  out[#out + 1] = "    },"
end
out[#out + 1] = "  },"
out[#out + 1] = "}"
out[#out + 1] = ""

local w = assert(io.open(OUT, "wb"))
w:write(table.concat(out, "\n"))
w:close()
print(("%s: %d version(s), %d item(s)%s"):format(OUT, #list, nItems,
  more and (" (" .. (#all - #list) .. " older left out)") or ""))
